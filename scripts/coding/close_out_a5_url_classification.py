#!/usr/bin/env python3
"""2026-09-12 A5 close-out.

A5 (URL classification) already ran (2026-09-05, fully cached) -- this
script does not call any LLM. It only formalizes two process guarantees
that were never honored: freezing the prompt (done separately, by content
hash -- see config/url_classification_prompt.yaml and the PROMPT_SHA256
assertion in analysis/coding/a5_url_classification.py) and drawing +
applying a human(-assisted) spot-check sample against the frozen
confidence threshold (0.70, user-decided).

Three steps, run in order:

  1. --sample        draw the spot-check sample from url_registry, write
                      data/03_coded/url_classification_spot_check.csv with
                      human_class/human_publisher_is_in_category/note blank.
  2. --dump-context   write data/03_coded/url_classification_context.json:
                      title/resolved-url/original-citation per sampled
                      url_normalized, exactly what A5 itself saw -- an aid
                      for the (AI-assisted) review pass in between steps 1
                      and 3. No review happens in this script; the CSV is
                      then hand-edited (Edit tool) in place.
  3. --apply          read the reviewed CSV, apply the narrow override rule
                      (a human label overrides the model only below
                      threshold, and only where one was recorded), write
                      settled_class/settled_publisher_is_in_category back
                      onto url_registry, export the frozen snapshot
                      data/03_coded/url_registry_frozen.csv, print the
                      agreement-rate summary, and checksum both artifacts
                      into data/03_coded/MANIFEST.json.

Usage:
    uv run python -m scripts.coding.close_out_a5_url_classification --sample
    uv run python -m scripts.coding.close_out_a5_url_classification --dump-context
    # ... review data/03_coded/url_classification_spot_check.csv by hand ...
    uv run python -m scripts.coding.close_out_a5_url_classification --apply
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import sqlite3
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from analysis.coding import storage
from analysis.coding.a5_url_classification import dedupe_sources_by_normalized_url
from analysis.coding.calibration import apply_overrides, compute_agreement
from analysis.coding.cited_url_resolution import load_resolution_map, resolve_sources_by_run
from analysis.coding.db import init_coding_schema
from collector.storage.db import get_connection
from scripts.aux._run import rel

from collector import paths
DEFAULT_DB_PATH = paths.CODING_DB
DEFAULT_SPOT_CHECK_CSV = paths.CODED_DIR / "url_classification_spot_check.csv"
DEFAULT_CONTEXT_JSON = paths.CODED_DIR / "url_classification_context.json"
DEFAULT_FROZEN_CSV = paths.CODED_DIR / "url_registry_frozen.csv"
DEFAULT_MANIFEST = paths.PHASE_A_MANIFEST

SPOT_CHECK_HEADER = (
    "# A5 close-out spot-check sample -- generated by "
    "scripts.coding.close_out_a5_url_classification --sample. Sorted ascending by "
    "confidence: below-threshold rows first (full review required), then a "
    "random calibration draw from the >= threshold band (review optional, "
    "measures trust only, never overrides). Hand-edit human_class / "
    "human_publisher_is_in_category / note in place; never regenerate with "
    "--sample after review starts."
)
SPOT_CHECK_COLUMNS = [
    "url_normalized",
    "classifier_confidence",
    "model_url_class",
    "model_publisher_is_in_category",
    "human_class",
    "human_publisher_is_in_category",
    "note",
]

FROZEN_HEADER = (
    "# Frozen url_registry snapshot -- generated by "
    "scripts.coding.close_out_a5_url_classification --apply. settled_* = human "
    "label where classifier_confidence was below threshold and a human "
    "label was recorded; otherwise settled_* passes the model label "
    "through unchanged. See data/02_aux/ambiguity_ledger.jsonl "
    "(a5-url-classification-close-out-2026-09-12) for the full account."
)
FROZEN_COLUMNS = [
    "url_normalized",
    "url_class",
    "publisher_is_in_category",
    "classifier_confidence",
    "settled_class",
    "settled_publisher_is_in_category",
]


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--db-path", type=Path, default=DEFAULT_DB_PATH)
    p.add_argument("--spot-check-csv", type=Path, default=DEFAULT_SPOT_CHECK_CSV)
    p.add_argument("--context-json", type=Path, default=DEFAULT_CONTEXT_JSON)
    p.add_argument("--frozen-csv", type=Path, default=DEFAULT_FROZEN_CSV)
    p.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    p.add_argument("--threshold", type=float, default=0.70)
    p.add_argument("--calibration-n", type=int, default=30)
    p.add_argument("--seed", type=int, default=20260912)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sample", action="store_true", help="step 1: draw the spot-check sample")
    mode.add_argument("--dump-context", action="store_true", help="step 2: write title/URL context for the sampled rows")
    mode.add_argument("--apply", action="store_true", help="step 3: apply overrides, freeze snapshot, checksum")
    return p.parse_args(argv)


def _fmt_bool(v: Any) -> str:
    if v in (None, ""):
        return ""
    return "True" if bool(int(v)) else "False"


def cmd_sample(args: argparse.Namespace) -> None:
    conn = get_connection(args.db_path)
    try:
        init_coding_schema(args.db_path)
        rows = storage.list_url_registry(conn=conn)
    finally:
        conn.close()

    scored = [r for r in rows if r.get("classifier_confidence") is not None]
    below = sorted((r for r in scored if r["classifier_confidence"] < args.threshold), key=lambda r: r["classifier_confidence"])
    above = [r for r in scored if r["classifier_confidence"] >= args.threshold]
    calibration_draw = sorted(
        random.Random(args.seed).sample(above, min(args.calibration_n, len(above))),
        key=lambda r: r["url_normalized"],
    )

    args.spot_check_csv.parent.mkdir(parents=True, exist_ok=True)
    with args.spot_check_csv.open("w", newline="", encoding="utf-8") as f:
        f.write(SPOT_CHECK_HEADER + "\n")
        writer = csv.DictWriter(f, fieldnames=SPOT_CHECK_COLUMNS)
        writer.writeheader()
        for r in below + calibration_draw:
            writer.writerow(
                {
                    "url_normalized": r["url_normalized"],
                    "classifier_confidence": r["classifier_confidence"],
                    "model_url_class": r.get("url_class") or "",
                    "model_publisher_is_in_category": _fmt_bool(r.get("publisher_is_in_category")),
                    "human_class": "",
                    "human_publisher_is_in_category": "",
                    "note": "",
                }
            )

    print(f"total url_registry rows: {len(rows)}")
    print(f"below threshold ({args.threshold}), full review required: {len(below)}")
    print(f"calibration draw from >= threshold ({len(above)} eligible): {len(calibration_draw)}")
    print(f"wrote {args.spot_check_csv} ({len(below) + len(calibration_draw)} rows)")


def _sources_by_run(conn: sqlite3.Connection) -> dict[str, list[dict[str, Any]]]:
    """Mirrors scripts/coding/run_coding_pipeline.py::_sources_by_run exactly --
    same query, so the context this dumps matches what A5 itself saw."""
    rows = conn.execute("SELECT run_id, position, url_raw, domain, title FROM sources ORDER BY run_id, position").fetchall()
    grouped: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        grouped.setdefault(row["run_id"], []).append(
            {"position": row["position"], "url_raw": row["url_raw"], "domain": row["domain"], "title": row["title"]}
        )
    return grouped


def cmd_dump_context(args: argparse.Namespace) -> None:
    with args.spot_check_csv.open(encoding="utf-8") as f:
        sampled = {row["url_normalized"] for row in csv.DictReader(line for line in f if not line.startswith("#"))}

    conn = get_connection(args.db_path)
    try:
        sources_by_run = _sources_by_run(conn)
    finally:
        conn.close()

    resolution_map = load_resolution_map()
    sources_by_run, _ = resolve_sources_by_run(sources_by_run, resolution_map)
    all_sources = [s for sources in sources_by_run.values() for s in sources]
    by_normalized = dedupe_sources_by_normalized_url(all_sources)

    context = {
        url: {
            "title": by_normalized[url].get("title"),
            "url_raw": by_normalized[url].get("url_raw"),
            "url_cited": by_normalized[url].get("url_cited"),
            "domain": by_normalized[url].get("domain"),
        }
        for url in sampled
        if url in by_normalized
    }
    missing = sampled - context.keys()

    args.context_json.parent.mkdir(parents=True, exist_ok=True)
    args.context_json.write_text(json.dumps(context, indent=2, sort_keys=True), encoding="utf-8")
    print(f"wrote {args.context_json} ({len(context)} of {len(sampled)} sampled URLs)")
    if missing:
        print(f"no source context found for {len(missing)} sampled URLs (likely resolution_dead placeholders): {sorted(missing)[:5]}...")


def _sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _manifest_entry(p: Path) -> dict[str, Any]:
    with p.open(encoding="utf-8") as f:
        lines = sum(1 for _ in f)
    return {"path": rel(p), "sha256": _sha256_file(p), "bytes": p.stat().st_size, "lines": lines}


def cmd_apply(args: argparse.Namespace) -> None:
    with args.spot_check_csv.open(encoding="utf-8") as f:
        spot_check_rows = list(csv.DictReader(line for line in f if not line.startswith("#")))

    conn = get_connection(args.db_path)
    try:
        init_coding_schema(args.db_path)

        overrides = apply_overrides(spot_check_rows, threshold=args.threshold)
        all_rows = storage.list_url_registry(conn=conn)
        settled_rows = []
        for r in all_rows:
            if r["url_normalized"] in overrides:
                settled_class, settled_pub = overrides[r["url_normalized"]]
            else:
                settled_class, settled_pub = r.get("url_class"), r.get("publisher_is_in_category")
            settled_rows.append(
                {"url_normalized": r["url_normalized"], "settled_class": settled_class, "settled_publisher_is_in_category": settled_pub}
            )
        storage.update_url_registry_settled(settled_rows, conn=conn)
        conn.commit()  # update_url_registry_settled doesn't commit when handed a shared conn

        frozen_rows = sorted(storage.list_url_registry(conn=conn), key=lambda r: r["url_normalized"])
    finally:
        conn.close()

    args.frozen_csv.parent.mkdir(parents=True, exist_ok=True)
    with args.frozen_csv.open("w", newline="", encoding="utf-8") as f:
        f.write(FROZEN_HEADER + "\n")
        writer = csv.DictWriter(f, fieldnames=FROZEN_COLUMNS)
        writer.writeheader()
        for r in frozen_rows:
            writer.writerow({col: r.get(col, "") if r.get(col) is not None else "" for col in FROZEN_COLUMNS})

    agreement = compute_agreement(spot_check_rows, threshold=args.threshold)
    n_null_settled = sum(1 for r in frozen_rows if r.get("settled_class") in (None, ""))

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "scripts/coding/close_out_a5_url_classification.py --apply",
        "artifacts": [_manifest_entry(args.frozen_csv), _manifest_entry(args.spot_check_csv)],
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")

    print(f"applied {len(overrides)} human overrides across {len(frozen_rows)} url_registry rows")
    print(f"rows with null settled_class after apply: {n_null_settled} (expect 0)")
    print(f"wrote {args.frozen_csv}")
    print(f"wrote {args.manifest}")
    print("agreement:", json.dumps(agreement, indent=2))


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    if args.sample:
        cmd_sample(args)
    elif args.dump_context:
        cmd_dump_context(args)
    elif args.apply:
        cmd_apply(args)


if __name__ == "__main__":
    main()
